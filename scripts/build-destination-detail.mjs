import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sources = [
  'js/services/apiClient.js',
  'js/services/reviewApi.js',
  'js/utils/dom.js',
  'js/utils/validate.js',
  'js/features/touristReviews.js',
  'js/main-destination-detail.js',
];

const parts = await Promise.all(sources.map(async (source) => {
  const code = await readFile(path.join(projectRoot, source), 'utf8');
  const transformed = code
    .replace(/^import .+;\n/gm, '')
    .replace(/^export /gm, '');
  if (/^(?:import|export) /m.test(transformed)) {
    throw new Error(`Unsupported module syntax in ${source}`);
  }
  return `// ${source}\n${transformed}`;
}));

const bundle = `/* Generated by scripts/build-destination-detail.mjs. Do not edit directly. */\n(() => {\n'use strict';\n${parts.join('\n')}\n})();\n`;
const output = path.join(projectRoot, 'destination-detail.bundle.js');

if (process.argv.includes('--check')) {
  const current = await readFile(output, 'utf8');
  if (current !== bundle) throw new Error('Destination detail bundle is out of date.');
} else {
  await writeFile(output, bundle);
}
